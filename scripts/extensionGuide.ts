// @effect-diagnostics nodeBuiltinImport:off - a build script, not server code.
/**
 * Builds the two extension guides that ship as documentation.
 *
 * Design §13: the guide is generated from what CI already tests, so it cannot
 * drift from the protocol or from the reference extension. Both outputs are
 * committed and byte-compared by a test; both are written to be readable on
 * their own, because they are what the MCP resources will hand an agent that
 * has no repository checkout.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import * as Schema from "effect/Schema";
import * as RpcSchema from "effect/unstable/rpc/RpcSchema";
import { EXTENSION_TOKEN_SCOPES, WsRpcGroup } from "@t3tools/contracts";

export const EXTENSION_GUIDE_DIR = "docs/internals/extensions";
export const GENERATE_COMMAND = "pnpm generate:extension-guide";

const repoRoot = NodePath.dirname(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)));

const PROTOCOL_SCHEMA_PATH = "packages/contracts/generated/extensions/protocol.schema.json";
const PROTOCOL_PROSE_PATH = `${EXTENSION_GUIDE_DIR}/protocol.md`;
const SCAFFOLD_PREAMBLE_PATH = "scripts/extension-guide/scaffold-preamble.md";
const REFERENCE_EXTENSION_DIR = "extensions/reference";

const read = (relativePath: string) =>
  NodeFS.readFileSync(NodePath.join(repoRoot, relativePath), "utf8");

const banner = (title: string, source: string) =>
  [
    `<!-- Generated by \`${GENERATE_COMMAND}\`. Do not edit. -->`,
    `<!-- Source: ${source} -->`,
    "",
    `# ${title}`,
    "",
  ].join("\n");

// ---------------------------------------------------------------------------
// JSON Schema rendering
// ---------------------------------------------------------------------------

interface JsonSchema {
  readonly $ref?: string;
  readonly type?: string;
  readonly enum?: ReadonlyArray<unknown>;
  readonly description?: string;
  readonly properties?: Record<string, JsonSchema>;
  readonly required?: ReadonlyArray<string>;
  readonly items?: JsonSchema;
  readonly anyOf?: ReadonlyArray<JsonSchema>;
  readonly allOf?: ReadonlyArray<JsonSchema>;
  readonly minLength?: number;
  readonly maxLength?: number;
  readonly pattern?: string;
  readonly minimum?: number;
  readonly maximum?: number;
  readonly maxItems?: number;
}

interface ProtocolSchema {
  readonly title: string;
  readonly description: string;
  readonly "x-protocolVersion": number;
  readonly "x-supportedProtocolVersions": ReadonlyArray<number>;
  readonly "x-methods": Record<string, ProtocolMethod>;
  readonly $defs: Record<string, JsonSchema>;
}

interface ProtocolMethod {
  readonly direction: string;
  readonly summary: string;
  readonly payload?: string;
  readonly success?: string;
  readonly errors?: ReadonlyArray<string>;
}

/** Markdown table cells cannot contain a raw pipe or a line break. */
const cell = (value: string) =>
  value
    .replaceAll("|", "\\|")
    .replaceAll(/\s*\n\s*/gu, " ")
    .trim();

const refName = (ref: string) => ref.replace("#/$defs/", "");

const literal = (value: unknown) => `\`${JSON.stringify(value)}\``;

/** A one-line type expression for a property, resolving `$ref` by name only. */
const renderType = (schema: JsonSchema): string => {
  if (schema.$ref !== undefined)
    return `[\`${refName(schema.$ref)}\`](#${anchor(refName(schema.$ref))})`;
  if (schema.enum !== undefined) return schema.enum.map(literal).join(" \\| ");
  if (schema.anyOf !== undefined) return schema.anyOf.map(renderType).join(" \\| ");
  if (schema.type === "array") {
    return schema.items === undefined ? "array" : `array of ${renderType(schema.items)}`;
  }
  if (schema.type === "object" && schema.properties !== undefined) {
    const fields = Object.keys(schema.properties).join(", ");
    return `object (${fields})`;
  }
  return schema.type ?? "unknown";
};

const constraintsOf = (schema: JsonSchema): string => {
  const sources: ReadonlyArray<JsonSchema> = [schema, ...(schema.allOf ?? [])];
  const parts: Array<string> = [];
  for (const source of sources) {
    if (source.minLength !== undefined) parts.push(`min length ${source.minLength}`);
    if (source.maxLength !== undefined) parts.push(`max length ${source.maxLength}`);
    if (source.minimum !== undefined) parts.push(`min ${source.minimum}`);
    if (source.maximum !== undefined) parts.push(`max ${source.maximum}`);
    if (source.maxItems !== undefined) parts.push(`max items ${source.maxItems}`);
    if (source.pattern !== undefined) parts.push(`pattern \`${source.pattern}\``);
  }
  return parts.join(", ");
};

/** GitHub-style heading anchor, so cross-references work in the single file. */
const anchor = (name: string) => name.toLowerCase();

/**
 * Constraints and descriptions are both sparse in the schema, so a column that
 * would be empty for every field is dropped rather than printed as a stripe of
 * blanks. It reappears on its own once the schema carries the values.
 */
const fieldTable = (schema: JsonSchema): ReadonlyArray<string> => {
  const properties = Object.entries(schema.properties ?? {});
  if (properties.length === 0) return ["No fields."];

  const required = new Set(schema.required ?? []);
  const columns = [
    { header: "Field", of: ([name]: [string, JsonSchema]) => `\`${name}\`` },
    { header: "Type", of: ([, property]: [string, JsonSchema]) => renderType(property) },
    {
      header: "Required",
      of: ([name]: [string, JsonSchema]) => (required.has(name) ? "yes" : "no"),
    },
    {
      header: "Constraints",
      of: ([, property]: [string, JsonSchema]) => cell(constraintsOf(property)),
    },
    {
      header: "Description",
      of: ([, property]: [string, JsonSchema]) => cell(property.description ?? ""),
    },
  ].filter((column) => properties.some((entry) => column.of(entry) !== ""));

  return [
    `| ${columns.map((column) => column.header).join(" | ")} |`,
    `| ${columns.map(() => "---").join(" | ")} |`,
    ...properties.map((entry) => `| ${columns.map((column) => column.of(entry)).join(" | ")} |`),
  ];
};

/**
 * Names a union variant by its discriminant, which every variant in this
 * protocol has — `type` for stream events, `_tag` for errors.
 */
const variantLabel = (variant: JsonSchema, index: number): string => {
  for (const key of ["type", "_tag", "kind"]) {
    const discriminant = variant.properties?.[key];
    if (discriminant?.enum?.length === 1) return `${key} = ${literal(discriminant.enum[0])}`;
  }
  return `variant ${index + 1}`;
};

const renderDefinition = (name: string, schema: JsonSchema): ReadonlyArray<string> => {
  const lines = [`### ${name}`, ""];
  if (schema.description !== undefined) lines.push(schema.description, "");

  if (schema.anyOf !== undefined) {
    lines.push(`One of ${schema.anyOf.length} shapes.`, "");
    schema.anyOf.forEach((variant, index) => {
      lines.push(`**${variantLabel(variant, index)}**`, "", ...fieldTable(variant), "");
    });
    return lines;
  }

  if (schema.properties !== undefined) {
    lines.push(...fieldTable(schema), "");
    return lines;
  }

  const constraints = constraintsOf(schema);
  const enumeration =
    schema.enum === undefined ? "" : ` One of: ${schema.enum.map(literal).join(", ")}.`;
  lines.push(
    `\`${schema.type ?? "unknown"}\`.${enumeration}${constraints === "" ? "" : ` Constraints: ${constraints}.`}`,
    "",
  );
  return lines;
};

const renderMethod = (name: string, method: ProtocolMethod): ReadonlyArray<string> => {
  const lines = [`### \`${name}\``, "", method.summary, ""];
  lines.push(`- Direction: ${method.direction}`);
  lines.push(
    `- Input: ${method.payload === undefined ? "none" : `[\`${method.payload}\`](#${anchor(method.payload)})`}`,
  );
  lines.push(
    `- Success: ${method.success === undefined ? "acknowledgement only" : `[\`${method.success}\`](#${anchor(method.success)})`}`,
  );
  const errors = method.errors ?? [];
  lines.push(
    `- Errors: ${errors.length === 0 ? "none" : errors.map((name) => `[\`${name}\`](#${anchor(name)})`).join(", ")}`,
  );
  lines.push("");
  return lines;
};

/**
 * Relative links in the prose only resolve next to `protocol.md`. The guide is
 * served on its own, so targets become repo-rooted paths; the sentences are
 * otherwise untouched.
 */
const absolutizeLinks = (markdown: string) =>
  markdown.replaceAll(
    /\]\((?!https?:\/\/|#|\/)([^)]+)\)/gu,
    // Normalized, so a link out of this directory (`../overview.md`) becomes
    // the repo path it means rather than one with `..` still in it.
    (_match, target: string) =>
      `](${NodePath.posix.normalize(`${EXTENSION_GUIDE_DIR}/${target}`)})`,
  );

const buildReference = (): string => {
  const schema = JSON.parse(read(PROTOCOL_SCHEMA_PATH)) as ProtocolSchema;
  const prose = absolutizeLinks(read(PROTOCOL_PROSE_PATH)).replace(/^# .*\n+/u, "");
  const { ExtensionManifest, ...rest } = schema.$defs;

  return [
    banner("Extension protocol reference", `${PROTOCOL_PROSE_PATH} + ${PROTOCOL_SCHEMA_PATH}`),
    `Protocol version ${schema["x-protocolVersion"]}. This host speaks ${schema["x-supportedProtocolVersions"].join(", ")}.`,
    "",
    prose.trimEnd(),
    "",
    "## Manifest",
    "",
    "The manifest an extension sends with `extensions.hello`.",
    "",
    ...renderDefinition("ExtensionManifest", ExtensionManifest!),
    "## Methods",
    "",
    ...Object.entries(schema["x-methods"]).flatMap(([name, method]) => renderMethod(name, method)),
    ...renderClientApi(),
    "## Definitions",
    "",
    ...Object.entries(rest).flatMap(([name, definition]) => renderDefinition(name, definition)),
  ]
    .join("\n")
    .replace(/\n{3,}/gu, "\n\n")
    .replace(/\n*$/u, "\n");
};

// ---------------------------------------------------------------------------
// Client API listing
// ---------------------------------------------------------------------------

/**
 * An extension is a client, so the whole client API is already available to it
 * — but nothing said so, and the first clean-room build read host source for
 * half its calls to find out what was there. This is the index that was
 * missing: every non-`extensions.*` method, what it takes, and what comes
 * back. Deliberately a listing rather than a reference; the shapes live in
 * `packages/contracts` and an author who needs a field reads them there.
 */

/**
 * Tagged error classes name their JSON shape `<Tag>Encoded`, which the vendored
 * artifacts already strip. Strip it here too so one name means one thing.
 */
const displayName = (name: string): string =>
  name.endsWith("Encoded") ? name.slice(0, -"Encoded".length) : name;

/** How many members of a union or fields of a struct are worth naming inline. */
const INLINE_LIMIT = 3;

const capped = (parts: ReadonlyArray<string>, separator: string): string => {
  const shown = parts.slice(0, INLINE_LIMIT).join(separator);
  return parts.length <= INLINE_LIMIT
    ? shown
    : `${shown}${separator}+${parts.length - INLINE_LIMIT}`;
};

/**
 * A one-line type expression. Named schemas keep their name; anything inline is
 * summarised by the part an author actually navigates by — a struct's field
 * names, a discriminated union's tags.
 */
const describeSchema = (schema: Schema.Top): string => {
  const root = Schema.toJsonSchemaDocument(schema).schema as JsonSchema & {
    readonly not?: unknown;
  };
  if (typeof root.$ref === "string") return `\`${displayName(refName(root.$ref))}\``;
  // `Schema.Never` (no error channel) and `Schema.Void` (nothing returned).
  if (root.not !== undefined || root.type === "null") return "—";

  if (Array.isArray(root.anyOf)) {
    const members = root.anyOf.filter(isJsonSchema);
    // `Schema.Struct({})` encodes as an unconstrained object-or-array union:
    // an empty payload, not a choice between two things.
    const carriesNothing = members.every(
      (member) =>
        member.$ref === undefined && member.properties === undefined && member.enum === undefined,
    );
    if (carriesNothing) return "—";

    const named = members.flatMap((member) =>
      typeof member.$ref === "string" ? [`\`${displayName(refName(member.$ref))}\``] : [],
    );
    if (named.length === members.length) return capped(named, " \\| ");

    // A discriminated union is far more useful listed by its tags than by the
    // fact that it is a union.
    const tags = members.flatMap((member) => {
      const discriminant =
        member.properties?.["_tag"] ?? member.properties?.["kind"] ?? member.properties?.["type"];
      return discriminant?.enum?.length === 1 ? [`\`${String(discriminant.enum[0])}\``] : [];
    });
    return tags.length === members.length ? capped(tags, " \\| ") : `union of ${members.length}`;
  }

  if (root.properties !== undefined) {
    const fields = Object.keys(root.properties);
    return fields.length === 0 ? "—" : `\`{${capped(fields, ", ")}}\``;
  }
  return `\`${root.type ?? "unknown"}\``;
};

const isJsonSchema = (value: unknown): value is JsonSchema =>
  typeof value === "object" && value !== null && !Array.isArray(value);

interface ClientMethod {
  readonly name: string;
  readonly stream: boolean;
  readonly payload: string;
  readonly success: string;
  readonly errors: string;
}

const clientMethods = (): ReadonlyArray<ClientMethod> =>
  [...WsRpcGroup.requests.entries()]
    .filter(([name]) => !name.startsWith("extensions."))
    .map(([name, rpc]) => {
      // A streaming RPC keeps its element and error schemas inside the stream
      // schema and leaves `errorSchema` as Never.
      const success = rpc.successSchema;
      const stream = RpcSchema.isStreamSchema(success);
      return {
        name,
        stream,
        payload: describeSchema(rpc.payloadSchema),
        success: describeSchema(stream ? success.success : success),
        errors: describeSchema(stream ? success.error : rpc.errorSchema),
      };
    });

const renderClientApi = (): ReadonlyArray<string> => {
  const methods = clientMethods();
  // A handful of methods carry no prefix at all (`subscribeVcsStatus`); they
  // are one group rather than one group each.
  const UNPREFIXED = "Ungrouped";
  const groups = new Map<string, Array<ClientMethod>>();
  for (const method of methods) {
    const dot = method.name.indexOf(".");
    const prefix = dot === -1 ? UNPREFIXED : `${method.name.slice(0, dot)}.`;
    const group = groups.get(prefix);
    if (group === undefined) groups.set(prefix, [method]);
    else group.push(method);
  }

  const scopes = EXTENSION_TOKEN_SCOPES.map((scope) => `\`${scope}\``).join(", ");

  return [
    "## Client API",
    "",
    "An extension is an ordinary client, so everything below is callable on the same socket",
    "as the `extensions.*` methods and needs no additional machinery. This is where an",
    "extension spawns work, sends messages, and reads state; the `extensions.*` surface only",
    "covers what has no client equivalent.",
    "",
    `Your token carries ${scopes}. The orchestration methods are open to you;`,
    "anything gated on a scope you were not granted — terminals, review, relay — answers",
    "with an authorization error rather than silently doing nothing.",
    "",
    `${methods.length} methods. This is an index, not a reference: payload and result shapes are`,
    "listed by name where they have one and by their fields or tags where they do not, and the",
    "full schemas live in the host's `packages/contracts`. A method marked **stream** returns a",
    "stream of the listed element rather than a single result.",
    "",
    ...[...groups].flatMap(([prefix, group]) => [
      prefix === UNPREFIXED ? `### ${prefix}` : `### \`${prefix}\``,
      "",
      "| Method | Payload | Result | Errors |",
      "| --- | --- | --- | --- |",
      ...group.map(
        (method) =>
          `| \`${method.name}\`${method.stream ? " **stream**" : ""} | ${method.payload} | ${method.success} | ${method.errors} |`,
      ),
      "",
    ]),
  ];
};

