/**
 * What a copied folder needs, in the order someone reads it: what it is, how
 * it is built, then the code. `protocol/` is excluded because it is a vendored
 * copy of generated artifacts (the preamble says where to get them), as are
 * the lockfile, the tests, and anything built.
 */
const SCAFFOLD_ROOT_FILES = [
  "package.json",
  "pnpm-workspace.yaml",
  "tsconfig.json",
  "build.mjs",
  ".gitignore",
] as const;

const LANGUAGE_BY_EXTENSION: Record<string, string> = {
  ".css": "css",
  ".json": "json",
  ".mjs": "js",
  ".ts": "ts",
  ".tsx": "tsx",
  ".yaml": "yaml",
};

const listSourceFiles = (directory: string): ReadonlyArray<string> =>
  NodeFS.readdirSync(NodePath.join(repoRoot, directory), { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name))
    .flatMap((entry) =>
      entry.isDirectory()
        ? listSourceFiles(`${directory}/${entry.name}`)
        : [`${directory}/${entry.name}`],
    );

const fencedFile = (relativePath: string): ReadonlyArray<string> => {
  const language = LANGUAGE_BY_EXTENSION[NodePath.extname(relativePath)] ?? "";
  const displayPath = relativePath.slice(`${REFERENCE_EXTENSION_DIR}/`.length);
  return [
    `### \`${displayPath}\``,
    "",
    `\`\`\`${language}`,
    read(relativePath).replace(/\n*$/u, ""),
    "```",
    "",
  ];
};

const buildScaffold = (): string => {
  const files = [
    ...SCAFFOLD_ROOT_FILES.map((name) => `${REFERENCE_EXTENSION_DIR}/${name}`),
    ...listSourceFiles(`${REFERENCE_EXTENSION_DIR}/src`),
  ];
  return [
    banner("Extension scaffold", `${SCAFFOLD_PREAMBLE_PATH} + ${REFERENCE_EXTENSION_DIR}/`),
    read(SCAFFOLD_PREAMBLE_PATH)
      .replace(/^# .*\n+/u, "")
      .trimEnd(),
    "",
    "## Files",
    "",
    ...files.flatMap(fencedFile),
  ]
    .join("\n")
    .replace(/\n{3,}/gu, "\n\n")
    .replace(/\n*$/u, "\n");
};

/**
 * Where the guide is also compiled into the server, so an agent can read it
 * over MCP from an installed build with no checkout anywhere near it.
 */
export const GUIDE_RESOURCES_DIR = "apps/server/src/extensions";
export const GUIDE_RESOURCES_FILE = "guideResources.generated.ts";

const guideResourcesModule = (reference: string, scaffold: string): string =>
  [
    `// Generated by \`${GENERATE_COMMAND}\` from ${EXTENSION_GUIDE_DIR}. Do not edit.`,
    "//",
    "// The two static extension guides, compiled in rather than read from disk:",
    "// the server ships as a bundle, and `docs/` is not part of it.",
    "",
    `export const EXTENSION_GUIDE_MARKDOWN = ${JSON.stringify(reference)};`,
    "",
    `export const EXTENSION_SCAFFOLD_MARKDOWN = ${JSON.stringify(scaffold)};`,
    "",
  ].join("\n");

export interface GuideArtifact {
  /** Repository-relative directory, because not every artifact is a doc. */
  readonly directory: string;
  readonly fileName: string;
  readonly contents: string;
}

export const buildExtensionGuideArtifacts = (): ReadonlyArray<GuideArtifact> => {
  const reference = buildReference();
  const scaffold = buildScaffold();
  return [
    { directory: EXTENSION_GUIDE_DIR, fileName: "reference.md", contents: reference },
    { directory: EXTENSION_GUIDE_DIR, fileName: "scaffold.md", contents: scaffold },
    {
      directory: GUIDE_RESOURCES_DIR,
      fileName: GUIDE_RESOURCES_FILE,
      contents: guideResourcesModule(reference, scaffold),
    },
  ];
};
